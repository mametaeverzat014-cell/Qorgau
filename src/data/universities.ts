/**
 * AdmitPath AI — curated university dataset.
 *
 * DATA HONESTY POLICY
 * -------------------
 * We did not scrape a global university database during a 72-hour hackathon and
 * we do not pretend that we did. This is a deliberately small, hand-curated set
 * of 35 institutions across 6 regions, chosen to exercise every branch of the
 * recommendation engine (full-ride providers, low-cost public systems, sticker-
 * price private universities, test-optional systems, English-taught programmes
 * in non-English-speaking countries).
 *
 * For every record:
 *   - `sources` links the official admissions / tuition / scholarship pages.
 *   - Requirements and aid policies are marked as PUBLISHED where the institution
 *     states them publicly; the UI labels them "Published requirement".
 *   - Every monetary figure is an INDICATIVE ESTIMATE for the 2026-27 cycle,
 *     marked `confidence: 'estimate'`, and the UI labels it as such. Costs change
 *     yearly and vary by programme; students must confirm at the source link.
 *   - Where we could not verify a value we store `null` with
 *     `confidence: 'unknown'` rather than inventing a number.
 *
 * Deadlines are the typical international undergraduate deadline for the cycle
 * and are shown in the UI with a "confirm at source" note.
 */

